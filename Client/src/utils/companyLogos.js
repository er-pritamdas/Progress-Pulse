/**
 * Resolves an entity name to a local crisp SVG or 512px asset if available.
 */
export function resolveLocalBrandLogo(name, type = "") {
  if (!name) return null;

  const raw = cleanKey(name);
  if (!raw) return null;

  // 1. Direct dictionary match
  if (LOCAL_BRAND_LOGOS[raw]) {
    return LOCAL_BRAND_LOGOS[raw];
  }

  // 2. Stripped common suffixes
  const stripped = raw
    .replace(
      /\b(mutual fund|mf|fund|scheme|deposit|rd|fd|bank|ltd|limited|pvt|private|corporation|group|holdings|services)\b/gi,
      ""
    )
    .replace(/\s+/g, " ")
    .trim();

  if (LOCAL_BRAND_LOGOS[stripped]) {
    return LOCAL_BRAND_LOGOS[stripped];
  }

  // 3. Substring match
  for (const [key, path] of Object.entries(LOCAL_BRAND_LOGOS)) {
    if (
      key.length >= 3 &&
      (raw === key ||
        raw.startsWith(key + " ") ||
        raw.includes(" " + key + " ") ||
        raw.endsWith(" " + key))
    ) {
      return path;
    }
  }

  // 4. Check if stripped is in bank logos
  if (type === "bank" || type === "fd" || type === "rd") {
    const bankSlug = stripped.replace(/[^a-z0-9]/g, "");
    if (LOCAL_BRAND_LOGOS[bankSlug]) {
      return LOCAL_BRAND_LOGOS[bankSlug];
    }
  }

  return null;
}

/**
 * High-level resolver that returns the best available logo source:
 * 1. Local pristine vector SVG / 512px asset
 * 2. High-res Google Favicon CDN
 * 3. Null (triggers monogram avatar)
 */
export function getBrandLogoSource(name, { domain = "", type = "" } = {}) {
  // 1. Check local high-definition brand asset first
  const localLogo = resolveLocalBrandLogo(name, type);
  if (localLogo) {
    return {
      src: localLogo,
      isLocal: true,
      domain: null,
    };
  }

  // 2. Fall back to resolved domain & Google High-Res CDN
  const resolvedDomain = resolveCompanyDomain(name, domain);
  if (resolvedDomain) {
    return {
      src: getCompanyLogoUrl(resolvedDomain, 128),
      isLocal: false,
      domain: resolvedDomain,
    };
  }

  return {
    src: null,
    isLocal: false,
    domain: null,
  };
}

/**
 * Normalizes an entity name into a search key.
 */
function cleanKey(str) {
  if (!str) return "";
  return String(str)
    .toLowerCase()
    .replace(/[^\w\s&.-]/g, "")
    .replace(/\s+/g, " ")
    .trim();
}

/**
 * Resolves a company/institution name into a website domain.
 */
export function resolveCompanyDomain(name, explicitDomain = "") {
  if (explicitDomain) return explicitDomain.trim();
  if (!name) return null;

  const raw = String(name).trim();

  // If the user entered a domain directly (e.g. "tcs.com")
  if (/^[a-zA-Z0-9-]+\.[a-zA-Z]{2,}(\.[a-zA-Z]{2,})?$/.test(raw)) {
    return raw.toLowerCase();
  }

  const cleaned = cleanKey(raw);

  // 1. Direct dictionary match
  if (BRAND_DOMAINS[cleaned]) {
    return BRAND_DOMAINS[cleaned];
  }

  // 2. Stripped common suffixes
  const stripped = cleaned
    .replace(
      /\b(ltd|limited|pvt|private|inc|corp|corporation|llc|llp|holdings|services|technologies|tech|solutions|india|bank|mutual fund|mf|fund|scheme|deposit|rd|fd)\b/gi,
      ""
    )
    .replace(/\s+/g, " ")
    .trim();

  if (BRAND_DOMAINS[stripped]) {
    return BRAND_DOMAINS[stripped];
  }

  // 3. Check for partial substring matches in dictionary
  for (const [key, domain] of Object.entries(BRAND_DOMAINS)) {
    if (key.length >= 3 && (cleaned === key || cleaned.startsWith(key + " ") || cleaned.includes(" " + key + " "))) {
      return domain;
    }
  }

  // 4. Check if stripped is valid as a generic .com
  const slug = stripped.replace(/[^a-z0-9]/gi, "");
  if (slug.length >= 3 && slug.length <= 25) {
    return `${slug}.com`;
  }

  return null;
}

/**
 * Generates the Google High-Res Favicon CDN URL.
 */
export function getCompanyLogoUrl(domain, size = 128) {
  if (!domain) return null;
  return `https://t2.gstatic.com/faviconV2?client=SOCIAL&type=FAVICON&fallback_opts=TYPE,SIZE,URL&url=https://${domain}&size=${size}`;
}

/**
 * Extracts 1-2 uppercase initials for the fallback monogram badge.
 */
export function getCompanyInitials(name) {
  if (!name) return "--";
  const words = String(name)
    .replace(/[^a-zA-Z0-9\s]/g, "")
    .trim()
    .split(/\s+/);
  if (words.length === 1) {
    return words[0].slice(0, 2).toUpperCase();
  }
  return (words[0].charAt(0) + words[1].charAt(0)).toUpperCase();
}

/**
 * Generates a deterministic, vibrant color palette for the monogram fallback.
 */
const MONOGRAM_PALETTES = [
  { bg: "bg-emerald-500/15 text-emerald-600 dark:text-emerald-400 border-emerald-500/25" },
  { bg: "bg-blue-500/15 text-blue-600 dark:text-blue-400 border-blue-500/25" },
  { bg: "bg-indigo-500/15 text-indigo-600 dark:text-indigo-400 border-indigo-500/25" },
  { bg: "bg-purple-500/15 text-purple-600 dark:text-purple-400 border-purple-500/25" },
  { bg: "bg-amber-500/15 text-amber-600 dark:text-amber-400 border-amber-500/25" },
  { bg: "bg-rose-500/15 text-rose-600 dark:text-rose-400 border-rose-500/25" },
  { bg: "bg-teal-500/15 text-teal-600 dark:text-teal-400 border-teal-500/25" },
  { bg: "bg-cyan-500/15 text-cyan-600 dark:text-cyan-400 border-cyan-500/25" },
  { bg: "bg-violet-500/15 text-violet-600 dark:text-violet-400 border-violet-500/25" },
];

export function getCompanyColorPalette(name) {
  if (!name) return MONOGRAM_PALETTES[0];
  let hash = 0;
  for (let i = 0; i < name.length; i++) {
    hash = name.charCodeAt(i) + ((hash << 5) - hash);
  }
  const index = Math.abs(hash) % MONOGRAM_PALETTES.length;
  return MONOGRAM_PALETTES[index];
}

